import { Pool } from "pg";

let pool: Pool | undefined;
let schemaReady: Promise<void> | undefined;

export function getPool(): Pool {
  if (!process.env.DATABASE_URL) throw new Error("DATABASE_URL is required for PostgreSQL storage");
  pool ??= new Pool({
    connectionString: process.env.DATABASE_URL,
    max: 5,
    ssl: process.env.PGSSLMODE === "disable" ? false : undefined,
  });
  return pool;
}

export async function ensureDatabaseSchema(): Promise<void> {
  if (!schemaReady)
    schemaReady = (async () => {
      await getPool().query(`
      CREATE TABLE IF NOT EXISTS jobpilot_jobs (
        id text PRIMARY KEY,
        data jsonb NOT NULL,
        created_at timestamptz NOT NULL DEFAULT now(),
        updated_at timestamptz NOT NULL DEFAULT now()
      );
      CREATE INDEX IF NOT EXISTS jobpilot_jobs_status_idx ON jobpilot_jobs ((data->>'status'));
      CREATE INDEX IF NOT EXISTS jobpilot_jobs_date_idx ON jobpilot_jobs ((data->>'dateFound'));
      CREATE TABLE IF NOT EXISTS jobpilot_runs (
        id text PRIMARY KEY,
        data jsonb NOT NULL,
        completed_at timestamptz NOT NULL
      );
      CREATE INDEX IF NOT EXISTS jobpilot_runs_completed_idx ON jobpilot_runs (completed_at DESC);
      CREATE TABLE IF NOT EXISTS jobpilot_profiles (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        data jsonb NOT NULL,
        created_at timestamptz NOT NULL DEFAULT now(),
        updated_at timestamptz NOT NULL DEFAULT now()
      );`);
    })();
  return schemaReady;
}
