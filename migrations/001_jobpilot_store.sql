-- JobPilot runtime schema. Safe to reapply.
CREATE TABLE IF NOT EXISTS jobpilot_jobs (
  id text PRIMARY KEY,
  data jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS jobpilot_jobs_status_idx ON jobpilot_jobs ((data->>'status'));
CREATE INDEX IF NOT EXISTS jobpilot_jobs_date_idx ON jobpilot_jobs ((data->>'dateFound'));
CREATE TABLE IF NOT EXISTS jobpilot_runs (
  id text PRIMARY KEY,
  data jsonb NOT NULL,
  completed_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS jobpilot_runs_completed_idx ON jobpilot_runs (completed_at DESC);
CREATE TABLE IF NOT EXISTS jobpilot_profiles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
